// 渗透作战条令：pentest / full 模式注入
// ---------------------------------------------------------------------------

const PENTEST_BLOCK = `【渗透作战条令】
- 侦察即建图：侦察的产出不是端口列表，而是攻击面地图——每个入口点标注认证要求、输入类型、可达的敏感汇聚点（sink）。
- Web/API 切片优先级：鉴权与会话（JWT 算法混淆、aud/iss 校验、会话固定）→ 访问控制（IDOR/BOLA、跨租户、管理端点缺失校验）→ 注入族（SQL/NoSQL/模板/命令/反序列化）→ 请求解析差异（smuggling、参数污染）→ 上传与文件处理 → SSRF/重定向 → 业务逻辑滥用。
- 确认即收束：oracle 一旦触发（canary 出现、伪造令牌 2xx、回调收到），立即确认该路径并转入下一条切片，不在一条路上反复刷量。
- 凭据与发现即时记录：拿到凭据、令牌、敏感配置立刻记入交战笔记，标注来源、可用范围与验证状态。`;

// ---------------------------------------------------------------------------
// 网络与协议逆向条令：reverse / full 模式注入（本套件重点）
// ---------------------------------------------------------------------------

const REVERSE_BLOCK = `【网络与协议逆向条令 — 本交战重点】
- 流量优先于反汇编：先抓真实流量（tcpdump / tshark / mitmproxy）建立协议基线，再带着问题进二进制。基线 = 正常握手与会话的完整消息序列样本。
- 消息结构推断：确定分帧方式（长度前缀 / 分隔符 / TLV / 固定头），多采样对比定位变化字段（计数器、时间戳、长度、校验和、加密块），判定字节序。每个字段语义都是待证伪的假设，不是结论。
- 状态机还原：握手→认证→会话→心跳→断开。先画出状态迁移图，再逐状态伪造消息实测服务端容忍度（乱序、重放、跳过认证态直接发业务消息）。
- 密码学识别与定位：用魔数与常量定位算法（r2 的 /iz、findcrypt 特征），严格区分加密、哈希与编码；查清密钥与 IV 来源（硬编码 / 密钥交换 / 口令派生）——密钥来源往往比算法本身更脆弱。
- 二进制薄切片：一次只逆一个功能单元（一个函数、一个消息处理器、一条协议消息）。循环：反编译 → 重命名 → 重建结构体 → 追 xrefs → 写注释。禁止全库泛读。
- 正确性闸门：每个结构假设用重放 / 篡改 / 伪造数据包实测验证。最终交付物是可运行的客户端或脚本——能跑通真实协议交互才算逆向完成，反编译"看起来对"不算。`;

/**
 * 按模式组装注入块。off 返回空串（调用方据此跳过注入）。
 * 非空块首行恒为幂等标记，供 handler 去重。
 */
export function buildPromptBlock(mode: RedkitMode): string {
	const parts =
		mode === "off"
			? []
			: mode === "pentest"
				? [CORE_BLOCK, PENTEST_BLOCK]
				: mode === "reverse"
					? [CORE_BLOCK, REVERSE_BLOCK]
					: [CORE_BLOCK, PENTEST_BLOCK, REVERSE_BLOCK];
	if (parts.length === 0) return "";
	return [REDKIT_INJECTION_MARKER, ...parts].join("\n\n");
}
